package io.github.kkami121.codeanalyzer.analysis;

/**
 * 코드 스타일 지표. 코드 리뷰에서 문서화와 일관성을 보는 데 쓴다.
 *
 * <p><b>이 값들은 사람이 썼는지 AI가 썼는지 판정하는 근거가 아니다.</b>
 * 작성자 판별은 신뢰할 수 있는 방법이 없고 오탐 위험이 크므로, 이 라이브러리는 그런 판정을 하지 않는다.
 */
public final class StyleProfile {

    public static final String NOTE = "Descriptive style indicators only. They are not evidence of whether "
            + "code was written by a person or generated by AI; no reliable method exists for that.";

    private final double commentRatio;
    private final double documentedFunctionRatio;
    private final double typedParameterRatio;
    private final double namingConsistency;
    private final String dominantNamingStyle;
    private final double averageIdentifierLength;
    private final double averageFunctionLines;

    StyleProfile(double commentRatio, double documentedFunctionRatio, double typedParameterRatio,
                 double namingConsistency, String dominantNamingStyle, double averageIdentifierLength,
                 double averageFunctionLines) {
        this.commentRatio = commentRatio;
        this.documentedFunctionRatio = documentedFunctionRatio;
        this.typedParameterRatio = typedParameterRatio;
        this.namingConsistency = namingConsistency;
        this.dominantNamingStyle = dominantNamingStyle;
        this.averageIdentifierLength = averageIdentifierLength;
        this.averageFunctionLines = averageFunctionLines;
    }

    /** 주석 줄 / 코드 줄. */
    public double commentRatio() {
        return commentRatio;
    }

    /** 독스트링(Python) 또는 Javadoc(Java)이 있는 함수 비율. */
    public double documentedFunctionRatio() {
        return documentedFunctionRatio;
    }

    /** 타입 표기가 있는 매개변수 비율 (self/cls 제외). Java는 항상 1. */
    public double typedParameterRatio() {
        return typedParameterRatio;
    }

    /** 함수/변수 이름이 가장 많이 쓰인 명명 규칙을 따르는 비율. */
    public double namingConsistency() {
        return namingConsistency;
    }

    /** snake_case, camelCase, PascalCase, UPPER_CASE 또는 none. */
    public String dominantNamingStyle() {
        return dominantNamingStyle;
    }

    public double averageIdentifierLength() {
        return averageIdentifierLength;
    }

    public double averageFunctionLines() {
        return averageFunctionLines;
    }
}
